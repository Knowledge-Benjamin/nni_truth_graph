const express = require('express');
const { b2bAuth } = require('../middleware/b2bAuth');
const path = require('path');
const fs = require('fs');
const router = express.Router();

// Enforce valid API key and dynamic rate limiting for all routes below
router.use(b2bAuth);

router.get('/claims', async (req, res) => {
    const { subject, min_score, limit = 100, offset = 0 } = req.query;
    
    let query = 'SELECT * FROM extracted_claims WHERE status = $1';
    let params = ['GRAPH_COMMITTED'];
    let paramCount = 1;

    // Optional Substring Filter
    if (subject) {
        paramCount++;
        query += ` AND subject ILIKE $${paramCount}`;
        params.push(`%${subject}%`);
    }
    
    // Optional Epistemic Trust Threshold Filter
    if (min_score) {
        paramCount++;
        query += ` AND epistemic_score >= $${paramCount}`;
        params.push(parseFloat(min_score));
    }

    paramCount++;
    // Hardcap limit to 1000 to prevent crashing the database
    query += ` ORDER BY created_at DESC LIMIT $${paramCount} OFFSET $${paramCount+1}`;
    params.push(Math.min(parseInt(limit), 1000));
    params.push(parseInt(offset));

    try {
        const result = await req.app.locals.pgPool.query(query, params);
        res.json({ 
            data: result.rows, 
            meta: { returned: result.rows.length, limit: parseInt(limit), offset: parseInt(offset) }
        });
    } catch (e) {
        console.error(e);
        res.status(500).json({ error: 'Database query failed' });
    }
});

router.get('/sources', async (req, res) => {
    try {
        const { limit = 100, offset = 0 } = req.query;
        // Returns the globally trusted sources leaderboard
        const result = await req.app.locals.pgPool.query(
            'SELECT name, domain, category, epistemic_trust_score FROM sources ORDER BY epistemic_trust_score DESC NULLS LAST LIMIT $1 OFFSET $2',
            [Math.min(parseInt(limit), 1000), parseInt(offset)]
        );
        res.json({ data: result.rows });
    } catch (e) {
        res.status(500).json({ error: 'Database query failed' });
    }
});

router.get('/datasets/daily-snapshot', (req, res) => {
    // Zero-cost Pragmatic Enterprise implementation: Serve local CSV snapshot
    const filePath = path.join(__dirname, '../../../data/truth_graph_snapshot.csv');
    if (!fs.existsSync(filePath)) {
        return res.status(404).json({ error: 'Daily snapshot not yet generated by processing engine.' });
    }
    res.download(filePath, `truth_graph_${new Date().toISOString().split('T')[0]}.csv`);
});

module.exports = router;
